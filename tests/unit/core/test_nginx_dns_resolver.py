"""Tests for the nginx DNS resolver selection in registry.core.nginx_service."""

import logging
from pathlib import Path

import pytest

from registry.core import nginx_service
from registry.core.nginx_service import (
    FALLBACK_NGINX_DNS_RESOLVER,
    MAX_RESOLV_CONF_NAMESERVERS,
    _get_nginx_dns_resolver,
    _read_resolv_conf_nameservers,
)

DOCKER_RESOLV_CONF: str = """# Generated by Docker Engine.
nameserver 127.0.0.11
search ec2.internal
options edns0 trust-ad ndots:0
"""


@pytest.fixture
def resolv_conf(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
):
    """Point the module at a temp resolv.conf and clear NGINX_DNS_RESOLVER."""
    path = tmp_path / "resolv.conf"
    monkeypatch.setattr(nginx_service, "RESOLV_CONF_PATH", str(path))
    monkeypatch.delenv("NGINX_DNS_RESOLVER", raising=False)
    return path


class TestReadResolvConfNameservers:
    """Parsing /etc/resolv.conf into nginx resolver addresses."""

    def test_reads_docker_embedded_dns(self, resolv_conf: Path):
        resolv_conf.write_text(DOCKER_RESOLV_CONF)

        assert _read_resolv_conf_nameservers(str(resolv_conf)) == ["127.0.0.11"]

    def test_wraps_ipv6_in_brackets(self, resolv_conf: Path):
        resolv_conf.write_text("nameserver 10.0.0.2\nnameserver fd00::53\n")

        assert _read_resolv_conf_nameservers(str(resolv_conf)) == ["10.0.0.2", "[fd00::53]"]

    def test_skips_zone_scoped_ipv6(self, resolv_conf: Path):
        resolv_conf.write_text("nameserver fe80::1%eth0\nnameserver 10.0.0.2\n")

        assert _read_resolv_conf_nameservers(str(resolv_conf)) == ["10.0.0.2"]

    def test_skips_values_that_are_not_ip_addresses(self, resolv_conf: Path):
        """A value that could break or inject into the nginx config is dropped."""
        resolv_conf.write_text(
            "nameserver 1.2.3.4;\n"
            "nameserver evil.example}\n"
            "nameserver 10.0.0.2 extra-field\n"
            "#nameserver 9.9.9.9\n"
            "nameserver\n"
        )

        assert _read_resolv_conf_nameservers(str(resolv_conf)) == ["10.0.0.2"]

    def test_keeps_at_most_three_nameservers(self, resolv_conf: Path):
        resolv_conf.write_text("".join(f"nameserver 10.0.0.{i}\n" for i in range(1, 6)))

        result = _read_resolv_conf_nameservers(str(resolv_conf))

        assert result == ["10.0.0.1", "10.0.0.2", "10.0.0.3"]
        assert len(result) == MAX_RESOLV_CONF_NAMESERVERS

    def test_missing_file_returns_empty(self, tmp_path: Path):
        assert _read_resolv_conf_nameservers(str(tmp_path / "absent")) == []


class TestGetNginxDnsResolver:
    """Precedence: env var, then resolv.conf, then public DNS."""

    def test_env_var_wins(
        self,
        resolv_conf: Path,
        monkeypatch: pytest.MonkeyPatch,
    ):
        resolv_conf.write_text(DOCKER_RESOLV_CONF)
        monkeypatch.setenv("NGINX_DNS_RESOLVER", "10.100.0.10")

        assert _get_nginx_dns_resolver() == "10.100.0.10"

    def test_blank_env_var_falls_through_to_resolv_conf(
        self,
        resolv_conf: Path,
        monkeypatch: pytest.MonkeyPatch,
    ):
        """A blank value (e.g. ${NGINX_DNS_RESOLVER:-}) must not emit `resolver  valid=10s`."""
        resolv_conf.write_text(DOCKER_RESOLV_CONF)
        monkeypatch.setenv("NGINX_DNS_RESOLVER", "   ")

        assert _get_nginx_dns_resolver() == "127.0.0.11"

    def test_uses_resolv_conf_when_env_unset(self, resolv_conf: Path):
        resolv_conf.write_text("nameserver 10.0.0.2\nnameserver 10.0.0.3\n")

        assert _get_nginx_dns_resolver() == "10.0.0.2 10.0.0.3"

    def test_falls_back_to_public_dns_with_warning(
        self,
        resolv_conf: Path,
        caplog: pytest.LogCaptureFixture,
    ):
        resolv_conf.write_text("search ec2.internal\n")

        with caplog.at_level(logging.WARNING, logger=nginx_service.logger.name):
            result = _get_nginx_dns_resolver()

        assert result == FALLBACK_NGINX_DNS_RESOLVER
        assert "falls back to public DNS" in caplog.text
